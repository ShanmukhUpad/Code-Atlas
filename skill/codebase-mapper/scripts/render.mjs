#!/usr/bin/env node
// Step 3 of the skill: merge the agent's explanations into the graph and write
// CODEBASE_MAP.md plus a self-contained skill-tree page, codebase-map.html.
// usage: node render.mjs <map-dir> [--md <path>] [--no-html]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { explainFile, explainFolder } from "./lib/atlas.mjs";

const args = process.argv.slice(2);
const dir = resolve(args.find((a, i) => !a.startsWith("--") && args[i - 1] !== "--md") ?? ".codebase-map");
const mdIdx = args.indexOf("--md");
const mdPath = resolve(mdIdx === -1 ? join(dir, "CODEBASE_MAP.md") : args[mdIdx + 1]);
const htmlPath = join(dir, "codebase-map.html");

const graph = JSON.parse(readFileSync(join(dir, "graph.json"), "utf8"));
const expPath = join(dir, "explanations.json");
const exp = existsSync(expPath) ? JSON.parse(readFileSync(expPath, "utf8")) : { items: [] };

const byPath = Object.fromEntries(graph.files.map((f) => [f.path, f]));
const written = new Map((exp.items ?? []).map((e) => [e.path, e]));
const explain = (path, kind) => {
  const e = written.get(path);
  if (e) return { summary: e.summary, role: e.role, source: "ai" };
  const h = kind === "folder"
    ? explainFolder(graph.folders.find((d) => d.path === path), byPath)
    : explainFile(byPath[path]);
  return { summary: h.summary, role: h.role, source: "heuristic" };
};

const ROLE_LABEL = {
  entry: "Entry point", hub: "Core module", orchestrator: "Coordinator", component: "Component",
  util: "Helper", config: "Config", file: "File",
};
const unknown = [...written.keys()].filter((p) => !byPath[p] && !graph.folders.some((d) => d.path === p));
if (unknown.length) console.warn(`Ignored explanations for paths not in the graph: ${unknown.join(", ")}`);

// ---- Markdown ----
const md = [];
md.push(`# ${graph.root}: codebase map`, "");
if (exp.overview) md.push(exp.overview.trim(), "");
const langs = [...new Set(graph.files.map((f) => f.lang))].join(", ");
md.push(`${graph.files.length} source files in ${graph.folders.length} folders (${langs}).`, "");

if (exp.readingOrder?.length) {
  md.push("## Where to start", "");
  exp.readingOrder.forEach((r, i) => md.push(`${i + 1}. \`${r.path}\`: ${r.why}`));
  md.push("");
}

// Folder-level dependency diagram, collapsed to the first two path segments.
const bucket = (p) => {
  const segs = p.split("/").slice(0, -1);
  return segs.length ? segs.slice(0, 2).join("/") : "(root)";
};
const edges = new Map();
for (const f of graph.files)
  for (const d of f.dependencies) {
    const a = bucket(f.path), b = bucket(d);
    if (a !== b) edges.set(`${a}\u0000${b}`, (edges.get(`${a}\u0000${b}`) ?? 0) + 1);
  }
const top = [...edges.entries()].sort((x, y) => y[1] - x[1]).slice(0, 40);
if (top.length) {
  const ids = new Map();
  const id = (name) => ids.get(name) ?? (ids.set(name, `n${ids.size}`), ids.get(name));
  md.push("## How the folders depend on each other", "", "```mermaid", "graph LR");
  for (const [key, n] of top) {
    const [a, b] = key.split("\u0000");
    md.push(`  ${id(a)}["${a}"] -->|${n}| ${id(b)}["${b}"]`);
  }
  md.push("```", "", "An arrow means files on the left import files on the right; the number counts the imports.", "");
}

md.push("## Folders", "");
for (const d of [...graph.folders].sort((a, b) => a.path.localeCompare(b.path))) {
  if (d.fileCount < 2 && d.path.includes("/")) continue;
  const e = explain(d.path, "folder");
  md.push(`### \`${d.path}/\``, "", e.role, "");
}

md.push("## Files", "", "| File | Role | Used by | Uses | What it does |", "| --- | --- | ---: | ---: | --- |");
const ranked = [...graph.files].sort((a, b) => b.fanIn - a.fanIn || a.path.localeCompare(b.path));
for (const f of ranked) {
  const e = explain(f.path, "file");
  md.push(`| \`${f.path}\` | ${ROLE_LABEL[f.role]} | ${f.fanIn} | ${f.fanOut} | ${e.summary.replace(/\|/g, "\\|")} |`);
}
md.push("", `_Generated by the codebase-mapper skill. ${written.size} explanations written by the agent; the rest are heuristics from the dependency graph._`, "");
writeFileSync(mdPath, md.join("\n"));

// ---- HTML ----
if (!args.includes("--no-html")) {
  // The page keeps the graph's role ("hub", …); the explanation's text goes in roleText.
  const explained = (path, kind) => {
    const { summary, role, source } = explain(path, kind);
    return { summary, roleText: role, source };
  };
  const data = {
    root: graph.root,
    overview: exp.overview ?? "",
    files: graph.files.map((f) => ({
      path: f.path, name: f.name, role: f.role, ext: f.ext, loc: f.loc,
      deps: f.dependencies, users: f.dependents, exports: f.exports.slice(0, 10),
      ...explained(f.path, "file"),
    })),
    folders: graph.folders.map((d) => ({ path: d.path, name: d.name, count: d.fileCount, ...explained(d.path, "folder") })),
  };
  const template = readFileSync(join(dirname(fileURLToPath(import.meta.url)), "lib", "viewer.html"), "utf8");
  const json = JSON.stringify(data).replace(/</g, "\\u003c");
  writeFileSync(htmlPath, template.replace("__TITLE__", escapeHtml(graph.root)).replace("__DATA__", () => json));
}

console.log(`Wrote ${relative(process.cwd(), mdPath)}`);
if (!args.includes("--no-html")) console.log(`Wrote ${relative(process.cwd(), htmlPath)}`);
console.log(`${written.size} agent explanations, ${graph.files.length + graph.folders.length - written.size} heuristic fallbacks.`);

function escapeHtml(s) {
  return s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
}
